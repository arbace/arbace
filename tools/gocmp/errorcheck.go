// gocmp errorcheck: the judge of goi's errorcheck programs (doc/go/GOI-SPEC.md, "As built:
// GR7b"). Its core is Go's test driver's, vendored from TamaGo's go1.27.1 tree,
// src/cmd/internal/testdir/testdir_test.go (splitOutput, errorCheck, wantedErrors,
// matchPrefix, partitionStrings, replacePrefix and the regexps of the // ERROR comments),
// with testing's t.Fatalf replaced by returned errors; the rest is Arbace's.

package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

const errorcheckUsage = `usage: gocmp errorcheck [-auto] FILE.go OUTPUT
       gocmp errorcheck -dump-errors DUMP.edn
Judges OUTPUT, a compiler's error lines (FILE:LINE: MESSAGE, gc's with -C; a
message's further lines indented by a tab), against the // ERROR "regexp"
comments of FILE.go as Go's test driver judges an errorcheck test: line by line,
every expected error matched by one of the errors on its line, and no error
left unmatched. -auto: errorcheckwithauto (the <autogenerated> lines are
expected by // ERRORAUTO). Prints pass, or fail and the judge's errors indented;
exit status 0 pass, 1 fail, 2 an error. -dump-errors prints the go/types errors
a godump dump holds (its :errors) in OUTPUT's format, columns dropped as -C
drops them.
`

func mainErrorcheck(args []string) int {
	fs := flag.NewFlagSet("gocmp errorcheck", flag.ExitOnError)
	auto := fs.Bool("auto", false, "errorcheckwithauto: <autogenerated> lines matched by // ERRORAUTO")
	dump := fs.String("dump-errors", "", "print the go/types errors of a godump dump (its :errors)")
	fs.Usage = usage(fs, errorcheckUsage)
	fs.Parse(args)
	if *dump != "" {
		errs, err := dumpErrors(*dump)
		if err != nil {
			fmt.Fprintln(os.Stderr, "gocmp errorcheck:", err)
			return 2
		}
		for _, e := range errs {
			fmt.Println(e)
		}
		return 0
	}
	if fs.NArg() != 2 {
		fs.Usage()
		return 2
	}
	file := fs.Arg(0)
	out, err := os.ReadFile(fs.Arg(1))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gocmp errorcheck:", err)
		return 2
	}
	if err := errorCheck(string(out), *auto, file, filepath.Base(file)); err != nil {
		fmt.Println("fail")
		for _, l := range strings.Split(strings.TrimSpace(err.Error()), "\n") {
			fmt.Println("\t" + l)
		}
		return 1
	}
	fmt.Println("pass")
	return 0
}

// dumpErrors reads the :errors vector of a godump dump (the strings as godump's out.str writes
// them: Go's escapes \" \\ \n \t and the like) and returns them as FILE:LINE: MESSAGE, the
// column dropped (gc's -C); a message's further lines indented by a tab, as gc prints them.
func dumpErrors(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<30)
	var line string
	for sc.Scan() {
		if l := sc.Text(); strings.HasPrefix(l, " :errors [") {
			line = strings.TrimPrefix(l, " :errors ")
			break
		}
		if strings.HasPrefix(sc.Text(), " :files") {
			break
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if line == "" {
		return nil, nil
	}
	var res []string
	rest := strings.TrimSpace(line)
	rest = strings.TrimPrefix(rest, "[")
	posRx := regexp.MustCompile(`^([^:\s]+):(\d+):\d+: `)
	for {
		rest = strings.TrimLeft(rest, " ")
		if rest == "" || rest[0] == ']' {
			break
		}
		if rest[0] != '"' {
			return nil, fmt.Errorf("%s: unexpected :errors entry: %.40s", path, rest)
		}
		q, err := strconv.QuotedPrefix(rest)
		if err != nil {
			return nil, fmt.Errorf("%s: %v", path, err)
		}
		s, err := strconv.Unquote(q)
		if err != nil {
			return nil, fmt.Errorf("%s: %v", path, err)
		}
		rest = rest[len(q):]
		s = posRx.ReplaceAllString(s, "$1:$2: ")
		res = append(res, strings.ReplaceAll(s, "\n", "\n\t"))
	}
	return res, nil
}

// From here to the end: Go's test driver, src/cmd/internal/testdir/testdir_test.go (go1.27.1).

func splitOutput(out string, wantAuto bool) []string {
	// gc error messages continue onto additional lines with leading tabs.
	// Split the output at the beginning of each line that doesn't begin with a tab.
	// <autogenerated> lines are impossible to match so those are filtered out.
	var res []string
	for _, line := range strings.Split(out, "\n") {
		if strings.HasSuffix(line, "\r") { // remove '\r', output by compiler on windows
			line = line[:len(line)-1]
		}
		if strings.HasPrefix(line, "\t") {
			res[len(res)-1] += "\n" + line
		} else if strings.HasPrefix(line, "go tool") || strings.HasPrefix(line, "#") || !wantAuto && strings.HasPrefix(line, "<autogenerated>") {
			continue
		} else if strings.TrimSpace(line) != "" {
			res = append(res, line)
		}
	}
	return res
}

// errorCheck matches errors in outStr against comments in source files.
// For each line of the source files which should generate an error,
// there should be a comment of the form // ERROR "regexp".
// If outStr has an error for a line which has no such comment,
// this function will report an error.
// Likewise if outStr does not have an error for a line which has a comment,
// or if the error message does not match the <regexp>.
// The <regexp> syntax is Perl but it's best to stick to egrep.
//
// Sources files are supplied as fullshort slice.
// It consists of pairs: full path to source file and its base name.
func errorCheck(outStr string, wantAuto bool, fullshort ...string) (err error) {
	var errs []error
	out := splitOutput(outStr, wantAuto)

	// Cut directory name.
	for i := range out {
		for j := 0; j < len(fullshort); j += 2 {
			full, short := fullshort[j], fullshort[j+1]
			out[i] = replacePrefix(out[i], full, short)
		}
	}

	var want []wantedError
	for j := 0; j < len(fullshort); j += 2 {
		full, short := fullshort[j], fullshort[j+1]
		we, err := wantedErrors(full, short)
		if err != nil {
			return err
		}
		want = append(want, we...)
	}

	for _, we := range want {
		var errmsgs []string
		if we.auto {
			errmsgs, out = partitionStrings("<autogenerated>", out)
		} else {
			errmsgs, out = partitionStrings(we.prefix, out)
		}
		if len(errmsgs) == 0 {
			errs = append(errs, fmt.Errorf("%s:%d: missing error %q", we.file, we.lineNum, we.reStr))
			continue
		}
		matched := false
		n := len(out)
		for _, errmsg := range errmsgs {
			// Assume errmsg says "file:line: foo".
			// Cut leading "file:line: " to avoid accidental matching of file name instead of message.
			text := errmsg
			if _, suffix, ok := strings.Cut(text, " "); ok {
				text = suffix
			}
			if we.re.MatchString(text) {
				matched = true
			} else {
				out = append(out, errmsg)
			}
		}
		if !matched {
			errs = append(errs, fmt.Errorf("%s:%d: no match for %#q in:\n\t%s", we.file, we.lineNum, we.reStr, strings.Join(out[n:], "\n\t")))
			continue
		}
	}

	if len(out) > 0 {
		// If a test uses -m and instantiates an imported generic function,
		// the errors will include messages for the instantiated function
		// with locations in the other package. Filter those out.
		localOut := make([]string, 0, len(out))
	outLoop:
		for _, errLine := range out {
			for j := 0; j < len(fullshort); j += 2 {
				full, short := fullshort[j], fullshort[j+1]
				if strings.HasPrefix(errLine, full+":") || strings.HasPrefix(errLine, short+":") {
					localOut = append(localOut, errLine)
					continue outLoop
				}
			}
		}
		out = localOut
	}

	if len(out) > 0 {
		errs = append(errs, fmt.Errorf("Unmatched Errors:"))
		for _, errLine := range out {
			errs = append(errs, fmt.Errorf("%s", errLine))
		}
	}

	if len(errs) == 0 {
		return nil
	}
	if len(errs) == 1 {
		return errs[0]
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "\n")
	for _, err := range errs {
		fmt.Fprintf(&buf, "%s\n", err.Error())
	}
	return errors.New(buf.String())
}

// matchPrefix reports whether s starts with file name prefix followed by a :,
// and possibly preceded by a directory name.
func matchPrefix(s, prefix string) bool {
	s = s[len(filepath.VolumeName(s)):]
	i := strings.Index(s, ":")
	if i < 0 {
		return false
	}
	j := strings.LastIndex(s[:i], string(filepath.Separator))
	s = s[j+1:]
	if len(s) <= len(prefix) || s[:len(prefix)] != prefix {
		return false
	}
	switch s[len(prefix)] {
	case '[', ':':
		return true
	}
	return false
}

func partitionStrings(prefix string, strs []string) (matched, unmatched []string) {
	for _, s := range strs {
		if matchPrefix(s, prefix) {
			matched = append(matched, s)
		} else {
			unmatched = append(unmatched, s)
		}
	}
	return
}

type wantedError struct {
	reStr   string
	re      *regexp.Regexp
	lineNum int
	auto    bool // match <autogenerated> line
	file    string
	prefix  string
}

var (
	errRx       = regexp.MustCompile(`// (?:GC_)?ERROR (.*)`)
	errAutoRx   = regexp.MustCompile(`// (?:GC_)?ERRORAUTO (.*)`)
	errQuotesRx = regexp.MustCompile(`"([^"]*)"`)
	lineRx      = regexp.MustCompile(`LINE(([+-])(\d+))?`)
)

func wantedErrors(file, short string) (errs []wantedError, err error) {
	cache := make(map[string]*regexp.Regexp)

	src, _ := os.ReadFile(file)
	for i, line := range strings.Split(string(src), "\n") {
		lineNum := i + 1
		if strings.Contains(line, "////") {
			// double comment disables ERROR
			continue
		}
		var auto bool
		m := errAutoRx.FindStringSubmatch(line)
		if m != nil {
			auto = true
		} else {
			m = errRx.FindStringSubmatch(line)
		}
		if m == nil {
			continue
		}
		all := m[1]
		mm := errQuotesRx.FindAllStringSubmatch(all, -1)
		if mm == nil {
			return nil, fmt.Errorf("%s:%d: invalid errchk line: %s", short, lineNum, line)
		}
		for _, m := range mm {
			rx := lineRx.ReplaceAllStringFunc(m[1], func(m string) string {
				n := lineNum
				if strings.HasPrefix(m, "LINE+") {
					delta, _ := strconv.Atoi(m[5:])
					n += delta
				} else if strings.HasPrefix(m, "LINE-") {
					delta, _ := strconv.Atoi(m[5:])
					n -= delta
				}
				return fmt.Sprintf("%s:%d", short, n)
			})
			re := cache[rx]
			if re == nil {
				var err error
				re, err = regexp.Compile(rx)
				if err != nil {
					return nil, fmt.Errorf("%s:%d: invalid regexp \"%s\" in ERROR line: %v", short, lineNum, rx, err)
				}
				cache[rx] = re
			}
			prefix := fmt.Sprintf("%s:%d", short, lineNum)
			errs = append(errs, wantedError{
				reStr:   rx,
				re:      re,
				prefix:  prefix,
				auto:    auto,
				lineNum: lineNum,
				file:    short,
			})
		}
	}

	return
}

func replacePrefix(s, old, new string) string {
	n := strings.Count(s, old)
	if n == 0 {
		return s
	}

	s = strings.ReplaceAll(s, " "+old, " "+new)
	s = strings.ReplaceAll(s, "\n"+old, "\n"+new)
	s = strings.ReplaceAll(s, "\n\t"+old, "\n\t"+new)
	if strings.HasPrefix(s, old) {
		s = new + s[len(old):]
	}
	return s
}
