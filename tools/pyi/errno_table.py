# errno_table.py OUT.go: the errno module's names and C's strerror texts (PY6e), go/arbace/py's builtins_errno_table.go,
# recorded from the oracle (CPython 3.14.10's errno and os.strerror on musl; tools/pydump/PYTHON_VERSION pins it).
# Linux's errno numbers are asm-generic's on amd64 and arm64 alike; the texts are musl's (src/errno/__strerror.h).
# Run: python3 -I -S -B tools/pyi/errno_table.py OUT.go
import errno
import os
import sys

out = sys.argv[1]
names = sorted(n for n in dir(errno) if n.startswith("E"))
codes = sorted(set(getattr(errno, n) for n in names))
with open(out, "w") as o:
    o.write("// Code generated by tools/pyi/errno_table.py from CPython %s's errno; DO NOT EDIT.\n\n" % sys.version.split()[0])
    o.write("package py\n\n")
    o.write("// errnoTable are errno's names and numbers, in name order.\n")
    o.write("var errnoTable = []struct {\n\tname string\n\tv    int\n}{\n")
    for n in names:
        o.write('\t{"%s", %d},\n' % (n, getattr(errno, n)))
    o.write("}\n\n")
    o.write("// errnoCodes are errno.errorcode: each number's name.\n")
    o.write("var errnoCodes = map[int]string{\n")
    for c in codes:
        o.write('\t%d: "%s",\n' % (c, errno.errorcode[c]))
    o.write("}\n\n")
    o.write("// strerrorTexts are C's strerror of each errno number (musl's).\n")
    o.write("var strerrorTexts = map[int]string{\n")
    for c in codes:
        o.write('\t%d: %s,\n' % (c, '"' + os.strerror(c).replace("\\", "\\\\").replace('"', '\\"') + '"'))
    o.write("}\n\n")
    o.write("// strerrorUnknown is strerror's text of a number it does not know.\n")
    o.write('const strerrorUnknown = "%s"\n' % os.strerror(99999))
