# textsig_table.py OUT.go: the built-in callables' and types' __text_signature__ (queue 290), go/arbace/py's
# builtins_textsig_table.go, recorded from the oracle (CPython 3.14.10: tools/pydump/PYTHON_VERSION pins it). CPython
# keeps a C callable's signature at the head of its docstring (Argument Clinic's "name(sig)\n--\n\n"), which pyi's
# built-ins do not carry: inspect.signature, pydoc and rlcompleter read it through __text_signature__.
#
# The modules walked: sys.builtin_module_names and the extension modules of the oracle's lib-dynload, but the test
# modules (_test*, xx*) and those that do not import; then every type reachable from them and from object's subclasses
# that C defines (a static type, or a heap type of one of those modules). The keys:
#   "type:MODULE.QUALNAME"            a type's __text_signature__ (object's "()", classmethod's "(function, /)")
#   "meth:MODULE.QUALNAME.NAME"       a callable in a C type's __dict__ (method_descriptor, classmethod_descriptor, a
#                                     staticmethod's or __new__'s builtin_function_or_method), as the descriptor has it
#   "func:MODULE.NAME"                a module's builtin_function_or_method
#   "slot:NAME"                       a slot wrapper's (typeobject.c's slotdefs: one per name; where types disagree,
#                                     object's, else the first type's in the walk's order)
# Only non-empty signatures are kept. Deterministic for a given oracle. Run: python3 -I -S -B tools/pyi/textsig_table.py OUT.go
import importlib
import importlib.machinery
import os
import sys

out = sys.argv[1]
HEAP = 1 << 9

names = set(sys.builtin_module_names)
for d in sys.path:
    if os.path.basename(d) == "lib-dynload" and os.path.isdir(d):
        for f in os.listdir(d):
            for sfx in importlib.machinery.EXTENSION_SUFFIXES:
                if f.endswith(sfx):
                    names.add(f[: -len(sfx)])
names = sorted(n for n in names if not n.startswith(("_test", "xx")) and n not in ("_tkinter", "__main__"))
mods = {}
for n in names:
    try:
        mods[n] = importlib.import_module(n)
    except Exception:
        pass
cmods = set(mods) | {"builtins"}


def tkey(t):
    m, q = getattr(t, "__module__", None), getattr(t, "__qualname__", None)
    if not isinstance(m, str) or not isinstance(q, str):
        return None
    return m + "." + q


def is_c_type(t):
    if not (t.__flags__ & HEAP):
        return True
    return getattr(t, "__module__", None) in cmods and all(
        not isinstance(v, type(tkey)) for v in vars(t).values())


types, seen = [], set()


def add_type(t):
    if id(t) in seen or not isinstance(t, type) or not is_c_type(t):
        return
    seen.add(id(t))
    types.append(t)


for n in sorted(mods):
    for a in sorted(vars(mods[n])):
        add_type(vars(mods[n])[a])
stack = [object]
while stack:
    t = stack.pop()
    add_type(t)
    try:
        stack.extend(reversed(type.__subclasses__(t)))
    except TypeError:
        pass

rows = {}


def put(k, s):
    if k is not None and isinstance(s, str) and s:
        rows.setdefault(k, s)


slots = {}
for t in types:
    k = tkey(t)
    if k is None:
        continue
    try:
        put("type:" + k, t.__text_signature__)
    except Exception:
        pass
    for a in sorted(vars(t)):
        v = vars(t)[a]
        if isinstance(v, (staticmethod, classmethod)) and not isinstance(v, type(dict.__dict__["fromkeys"])):
            v = v.__func__
        tn = type(v).__name__
        if tn in ("method_descriptor", "classmethod_descriptor", "builtin_function_or_method"):
            put("meth:" + k + "." + a, getattr(v, "__text_signature__", None))
        elif tn == "wrapper_descriptor":
            s = getattr(v, "__text_signature__", None)
            if s:
                slots.setdefault(a, []).append((t is object, s))
for a, ss in slots.items():
    obj = [s for o, s in ss if o]
    put("slot:" + a, obj[0] if obj else ss[0][1])
for n in sorted(mods):
    m = mods[n]
    for a in sorted(vars(m)):
        v = vars(m)[a]
        if type(v).__name__ == "builtin_function_or_method" and getattr(v, "__self__", None) is m:
            put("func:" + n + "." + a, v.__text_signature__)


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


with open(out, "w") as o:
    o.write("// Code generated by tools/pyi/textsig_table.py from CPython %s's built-ins; DO NOT EDIT.\n\n" % sys.version.split()[0])
    o.write("package py\n\n")
    o.write("// textSigs are CPython's __text_signature__ of its built-in types (type:), the callables in their dicts (meth:),\n")
    o.write("// the modules' functions (func:) and the slot wrappers (slot:), by the type's or module's qualified name\n")
    o.write("var textSigs = map[string]string{\n")
    for k in sorted(rows):
        o.write("\t%s: %s,\n" % (q(k), q(rows[k])))
    o.write("}\n")
