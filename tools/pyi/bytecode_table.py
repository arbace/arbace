# bytecode_table.py TOP OUT.go (queue 229): go/arbace/py's bytecode_table.go, the tables of pyi's view of CPython's bytecode
# (bytecode.go): the real and pseudo opcodes of Include/opcode_ids.h that are not specializations, their inline caches and
# stack effects, from Include/internal/pycore_opcode_metadata.h. TOP is the pinned tarball's tree (tools/pydump/PYTHON_VERSION).
# Run: python3 -I -S -B tools/pyi/bytecode_table.py TOP OUT.go
# Queue 238 (doc/PY315-SURVEY.md P5): with --suffix 315 --base TOP314, the table of another release (3.15.2's tree as TOP)
# for the version switch (go/arbace/py/version.ae): pyi's view names an instruction by 3.14's constants (TOP314's table, the
# file without the suffix) whatever the release, so this file maps them to the release's numbers (bcNumSUFFIX), its caches,
# names and stack effects; an opcode TOP314 has not gets a constant of its own, 1000 plus its number.
import re
import sys


def table(top):
    ids = open(top + "/Include/opcode_ids.h").read()
    meta = open(top + "/Include/internal/pycore_opcode_metadata.h").read()
    ops = {m[1]: int(m[2]) for m in re.finditer(r"#define ([A-Z_0-9]+) +(\d+)$", ids, re.M) if m[1] not in ("HAVE_ARGUMENT", "MIN_SPECIALIZED_OPCODE", "MIN_INSTRUMENTED_OPCODE")}
    ops = {k: v for k, v in ops.items() if not k.startswith("INSTRUMENTED_")}
    deopt = dict(re.findall(r"\[([A-Z_0-9]+)\] = ([A-Z_0-9]+),", meta[meta.index("_PyOpcode_Deopt[256] = {"):meta.index("};", meta.index("_PyOpcode_Deopt[256] = {"))]))
    keep = {k: v for k, v in ops.items() if deopt.get(k, k) == k}
    caches = dict(re.findall(r"\[([A-Z_0-9]+)\] = (\d+),", meta[meta.index("_PyOpcode_Caches[256] = {"):meta.index("};", meta.index("_PyOpcode_Caches[256] = {"))]))
    return meta, keep, caches


args = sys.argv[1:]
suffix = base = None
if "--suffix" in args:
    i = args.index("--suffix")
    suffix = args[i + 1]
    del args[i:i + 2]
if "--base" in args:
    i = args.index("--base")
    base = args[i + 1]
    del args[i:i + 2]
top, out = args[0], args[1]
meta, keep, caches = table(top)


def effects(name):
    s = meta[meta.index("int %s(int opcode, int oparg)  {" % name):]
    s = s[:s.index("default:")]
    return {m[1]: m[2] for m in re.finditer(r"case ([A-Z_0-9]+):\n\s+return (.*?);", s)}


popped, pushed = effects("_PyOpcode_num_popped"), effects("_PyOpcode_num_pushed")
flags = {m[1]: m[2] for m in re.finditer(r"\[([A-Z_0-9]+)\] = \{ [^,]*, [^,]*, ([^}]*) \},", meta)}


def switch(o, fn, table):
    o.write("func %s(op, oparg int) int {\n\tswitch op {\n" % fn)
    by = {}
    for k in sorted(keep, key=keep.get):
        if k in table:
            by.setdefault(table[k], []).append("bc" + k)
    for e, ks in sorted(by.items()):
        o.write("\tcase %s:\n\t\treturn %s\n" % (", ".join(ks), e))
    o.write("\t}\n\treturn 0\n}\n\n")


if suffix:
    if not base:
        sys.exit("bytecode_table.py: --suffix needs --base TOP314 (the table pyi's constants are)")
    release = ".".join(re.search(r"#define PY_%s_VERSION\s+(\d+)" % k, open(top + "/Include/patchlevel.h").read())[1] for k in ("MAJOR", "MINOR", "MICRO"))
    known = table(base)[1]
    new = sorted((k for k in keep if k not in known), key=keep.get)

    with open(out, "w") as o:
        o.write("// Code generated by tools/pyi/bytecode_table.py --suffix %s from CPython %s's opcode_ids.h and pycore_opcode_metadata.h; DO NOT EDIT.\n\n" % (suffix, release))
        o.write("package py\n\n")
        if new:
            o.write("// The opcodes CPython %s adds to 3.14's (pyi's view never emits them): 1000 plus their number.\nconst (\n" % release)
            for k in new:
                o.write("\tbc%s = %d\n" % (k, 1000 + keep[k]))
            o.write(")\n\n")
        o.write("// bcNum%s is each opcode's number in CPython %s, by pyi's constant (an opcode absent from %s has none).\nvar bcNum%s = map[int]int{" % (suffix, release, release, suffix))
        o.write(", ".join("bc%s: %d" % (k, keep[k]) for k in sorted(keep, key=keep.get)))
        o.write("}\n\n// bcCaches%s is _PyOpcode_Caches: each opcode's inline cache entries.\nvar bcCaches%s = map[int]int{" % (suffix, suffix))
        o.write(", ".join("bc%s: %s" % kv for kv in caches.items()))
        o.write("}\n\n// bcNames%s are the opcodes' names.\nvar bcNames%s = map[int]string{" % (suffix, suffix))
        o.write(", ".join('bc%s: "%s"' % (k, k) for k in sorted(keep, key=keep.get)))
        o.write("}\n\n")
        switch(o, "bcPopped" + suffix, popped)
        switch(o, "bcPushed" + suffix, pushed)
    sys.exit(0)

with open(out, "w") as o:
    o.write("// Code generated by tools/pyi/bytecode_table.py from CPython 3.14.10's opcode_ids.h and pycore_opcode_metadata.h; DO NOT EDIT.\n\n")
    o.write("package py\n\n// CPython 3.14's opcodes, the specializations left out.\nconst (\n")
    for k, v in sorted(keep.items(), key=lambda kv: kv[1]):
        o.write("\tbc%s = %d\n" % (k, v))
    o.write(")\n\n// bcCaches is _PyOpcode_Caches: each opcode's inline cache entries.\nvar bcCaches = map[int]int{")
    o.write(", ".join("bc%s: %s" % kv for kv in caches.items()))
    o.write("}\n\n// bcNames are the opcodes' names.\nvar bcNames = map[int]string{")
    o.write(", ".join('bc%s: "%s"' % (k, k) for k in sorted(keep, key=keep.get)))
    o.write("}\n\n")
    switch(o, "bcPopped", popped)
    switch(o, "bcPushed", pushed)
