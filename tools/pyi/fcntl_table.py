# fcntl_table.py GOROOT OUT.go: the fcntl module's integer constants (PY6e), go/arbace/py's builtins_fcntl_table.go,
# recorded from the oracle (CPython 3.14.10's own fcntl; tools/pydump/PYTHON_VERSION pins it). A constant Go's syscall
# declares for both linux/amd64 and linux/arm64 (GOROOT/src/syscall/zerrors_linux_ARCH.go) is written as syscall's
# name, so each architecture compiles its own value (the generator checks it equals the oracle's here); the others are
# Linux's generic UAPI and musl's values, the same on both, written as numbers.
# Run: python3 -I -S -B tools/pyi/fcntl_table.py /root/tamago-go tools-out.go
import re
import sys
import fcntl as _socket

goroot, out = sys.argv[1], sys.argv[2]
src = {a: open("%s/src/syscall/zerrors_linux_%s.go" % (goroot, a)).read() for a in ("amd64", "arm64")}
arch = {"x86_64": "amd64", "aarch64": "arm64"}[__import__("os").uname().machine]


def gov(a, n):
    m = re.search(r"\n\s+%s\s+= (0x[0-9a-fA-F]+|-?\d+)\n" % n, src[a])
    return int(m.group(1), 0) if m else None


rows = []
for n in sorted(dir(_socket)):
    v = getattr(_socket, n)
    if type(v) is not int:
        continue
    if gov("amd64", n) is not None and gov("arm64", n) is not None:
        if gov(arch, n) != v:
            sys.exit("fcntl_table: %s: syscall's %d, the oracle's %d" % (n, gov(arch, n), v))
        rows.append('\t{"%s", syscall.%s},\n' % (n, n))
    else:
        rows.append('\t{"%s", %d},\n' % (n, v))

with open(out, "w") as o:
    o.write("// Code generated by tools/pyi/fcntl_table.py from CPython %s's fcntl; DO NOT EDIT.\n\n" % sys.version.split()[0])
    o.write("package py\n\nimport \"syscall\"\n\n")
    o.write("// fcntlConsts are fcntl's integer constants, in name order: syscall's where it declares them.\n")
    o.write("var fcntlConsts = []struct {\n\tname string\n\tv    int64\n}{\n")
    o.write("".join(rows))
    o.write("}\n")
