# asdl_table.py PYTHON_SRC OUT.go: the _ast module's node table (PY6a), go/arbace/py's builtins_ast_table.go, from
# CPython 3.14.10's Parser/Python.asdl read by its own Parser/asdl.py (the pinned tarball's). Each line:
#   sum NAME ATTRIBUTES          an abstract node class (expr, stmt ...), its _attributes
#   con NAME BASE FIELDS         a constructor of a sum type (BASE), its _fields
#   pro NAME FIELDS ATTRIBUTES   a product type (arguments, keyword ...)
# FIELDS and ATTRIBUTES: comma-separated name:type:q (q: "" one, "?" optional, "*" sequence), "-" when none.
# Run: python3 -I -S -B tools/pyi/asdl_table.py .tmp/repr-python/Python-3.14.10 OUT.go
# The header names the tree's release (Include/patchlevel.h's PY_VERSION; queue 236): 3.15.2's tree gives 3.15's table
# (is_lazy of Import and ImportFrom, DictComp's optional value), the runtime's when pyi moves to 3.15 (PY315-SURVEY P3).
# Since queue 350 the runtime's table is Arbace's (tools/pyi/runtime_tables.ae ast, bin/pyi runtime gen-tables): this is the
# oracle's, run by hand; since queue 366 the committed file's header names that generator, so this one's output differs from it in
# the first line alone.
import re
import sys

src, out = sys.argv[1], sys.argv[2]
sys.path.insert(0, src + "/Parser")
import asdl  # noqa: E402

m = asdl.parse(src + "/Parser/Python.asdl")


def fields(fs):
    parts = []
    for f in fs:
        q = "*" if f.seq else ("?" if f.opt else "")
        parts.append("%s:%s:%s" % (f.name, f.type, q))
    return ",".join(parts) or "-"


lines = []
for d in m.dfns:
    v = d.value
    if isinstance(v, asdl.Sum):
        lines.append("sum %s %s" % (d.name, fields(v.attributes)))
        for c in v.types:
            lines.append("con %s %s %s" % (c.name, d.name, fields(c.fields)))
    else:
        lines.append("pro %s %s %s" % (d.name, fields(v.fields), fields(v.attributes)))
version = re.search(r'#define\s+PY_VERSION\s+"([0-9.]+)', open(src + "/Include/patchlevel.h").read()).group(1)
with open(out, "w") as o:
    o.write("// Code generated by tools/pyi/asdl_table.py from CPython %s's Parser/Python.asdl; DO NOT EDIT.\n\n" % version)
    o.write("package py\n\n")
    o.write("// astTable is the _ast module's node classes (PY6a): see tools/pyi/asdl_table.py for the format.\n")
    o.write("const astTable = `" + "\n".join(lines) + "\n`\n")
