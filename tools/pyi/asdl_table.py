import sys

src, out = sys.argv[1], sys.argv[2]
sys.path.insert(0, src + "/Parser")
import asdl  # noqa: E402

m = asdl.parse(src + "/Parser/Python.asdl")


def fields(fs):
    parts = []
    for f in fs:
        q = "*" if f.seq else ("?" if f.opt else "")
        parts.append("%s:%s:%s" % (f.name, f.type, q))
    return ",".join(parts) or "-"


lines = []
for d in m.dfns:
    v = d.value
    if isinstance(v, asdl.Sum):
        lines.append("sum %s %s" % (d.name, fields(v.attributes)))
        for c in v.types:
            lines.append("con %s %s %s" % (c.name, d.name, fields(c.fields)))
    else:
        lines.append("pro %s %s %s" % (d.name, fields(v.fields), fields(v.attributes)))
with open(out, "w") as o:
    o.write("// Code generated by tools/pyi/asdl_table.py from CPython 3.14.10's Parser/Python.asdl; DO NOT EDIT.\n\n")
    o.write("package py\n\n")
    o.write("// astTable is the _ast module's node classes (PY6a): see tools/pyi/asdl_table.py for the format.\n")
    o.write("const astTable = `" + "\n".join(lines) + "\n`\n")
