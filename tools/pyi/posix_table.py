# posix_table.py GOROOT OUT.go: the posix module's integer constants and its sysconf, confstr and pathconf names (PY6e),
# go/arbace/py's builtins_posix_table.go, recorded from the oracle (CPython 3.14.10's own posix on musl;
# tools/pydump/PYTHON_VERSION pins it). A constant Go's syscall declares for both linux/amd64 and linux/arm64 with musl's
# value is written as syscall's name (each architecture compiles its own); MUSL_ARCH's are musl's own per architecture
# (arch/{x86_64,aarch64}/bits/fcntl.h, where Go's syscall differs or is silent); the rest are Linux's generic values and
# musl's, the same on both, written as numbers. The generator checks every value equals the oracle's on this machine.
# Run: python3 -I -S -B tools/pyi/posix_table.py /root/tamago-go OUT.go, then gofmt -w OUT.go
import os
import re
import sys
import posix

goroot, out = sys.argv[1], sys.argv[2]
src = {a: open("%s/src/syscall/zerrors_linux_%s.go" % (goroot, a)).read() for a in ("amd64", "arm64")}
arch = {"x86_64": "amd64", "aarch64": "arm64"}[os.uname().machine]
MUSL_ARCH = {"O_LARGEFILE": {"amd64": 0o100000, "arm64": 0o400000},
             "O_TMPFILE": {"amd64": 0o20200000, "arm64": 0o20040000},
             "O_ACCMODE": {"amd64": 0o10000003, "arm64": 0o10000003}}


def gov(a, n):
    m = re.search(r"\n\s+%s\s+= (0x[0-9a-fA-F]+|-?\d+)\n" % n, src[a])
    return int(m.group(1), 0) if m else None


rows = []
for n in sorted(dir(posix)):
    v = getattr(posix, n)
    if type(v) is not int:
        continue
    if n in MUSL_ARCH:
        if MUSL_ARCH[n][arch] != v:
            sys.exit("posix_table: %s: musl's %d, the oracle's %d" % (n, MUSL_ARCH[n][arch], v))
        rows.append('\t{"%s", archConst(%d, %d)},\n' % (n, MUSL_ARCH[n]["amd64"], MUSL_ARCH[n]["arm64"]))
    elif gov("amd64", n) is not None and gov("arm64", n) is not None:
        if gov(arch, n) != v:
            sys.exit("posix_table: %s: syscall's %d, the oracle's %d" % (n, gov(arch, n), v))
        rows.append('\t{"%s", syscall.%s},\n' % (n, n))
    else:
        rows.append('\t{"%s", %d},\n' % (n, v))


def names(var, d, doc):
    s = "// %s\nvar %s = []struct {\n\tname string\n\tv    int\n}{\n" % (doc, var)
    for k in sorted(d):
        s += '\t{"%s", %d},\n' % (k, d[k])
    return s + "}\n\n"


# sysconf's values that musl computes at run time (rlimits, the machine, the auxiliary vector): computed by pyi
DYNAMIC = {"SC_ARG_MAX", "SC_AVPHYS_PAGES", "SC_CHILD_MAX", "SC_NPROCESSORS_CONF", "SC_NPROCESSORS_ONLN", "SC_OPEN_MAX",
           "SC_PHYS_PAGES", "SC_PAGESIZE", "SC_PAGE_SIZE", "SC_MINSIGSTKSZ"}
static = {}
for k in posix.sysconf_names:
    if k not in DYNAMIC:
        static[k] = posix.sysconf(k)
paths = {k: posix.pathconf("/", k) for k in posix.pathconf_names}
confs = {}
for k in posix.confstr_names:
    try:
        confs[k] = posix.confstr(k)
    except OSError:
        confs[k] = None

with open(out, "w") as o:
    o.write("// Code generated by tools/pyi/posix_table.py from CPython %s's posix; DO NOT EDIT.\n\n" % sys.version.split()[0])
    o.write("package py\n\nimport (\n\t\"runtime\"\n\t\"syscall\"\n)\n\n")
    o.write("// posixConsts are posix's integer constants, in name order.\n")
    o.write("var posixConsts = []struct {\n\tname string\n\tv    int64\n}{\n")
    o.write("".join(rows))
    o.write("}\n\n")
    o.write("// archConst is musl's value of a constant on amd64 or arm64.\n")
    o.write("func archConst(amd64, arm64 int64) int64 {\n\tif runtime.GOARCH == \"amd64\" {\n\t\treturn amd64\n\t}\n\treturn arm64\n}\n\n")
    o.write(names("sysconfNames", posix.sysconf_names, "sysconfNames are os.sysconf_names (musl's _SC_ numbers)."))
    o.write(names("confstrNames", posix.confstr_names, "confstrNames are os.confstr_names."))
    o.write(names("pathconfNames", posix.pathconf_names, "pathconfNames are os.pathconf_names."))
    o.write("// sysconfStatic are musl's sysconf values of its static table (by _SC_ number), the dynamic ones computed.\n")
    o.write("var sysconfStatic = map[int]int64{\n")
    seen = set()
    for k in sorted(static, key=lambda k: (posix.sysconf_names[k], k)):
        if posix.sysconf_names[k] in seen:
            continue
        seen.add(posix.sysconf_names[k])
        o.write("\t%d: %d, // %s\n" % (posix.sysconf_names[k], static[k], k))
    o.write("}\n\n")
    o.write("// pathconfStatic are musl's fpathconf values (a static table: the same for every file).\n")
    o.write("var pathconfStatic = map[int]int64{\n")
    seen = set()
    for k in sorted(paths, key=lambda k: (posix.pathconf_names[k], k)):
        if posix.pathconf_names[k] in seen:
            continue
        seen.add(posix.pathconf_names[k])
        o.write("\t%d: %d, // %s\n" % (posix.pathconf_names[k], paths[k], k))
    o.write("}\n\n")
    o.write("// confstrValues are musl's confstr values; absent: EINVAL.\n")
    o.write("var confstrValues = map[int]string{\n")
    for k in sorted(confs):
        if confs[k] is not None:
            o.write('\t%d: "%s", // %s\n' % (posix.confstr_names[k], confs[k], k))
    o.write("}\n")
