# opcode_table.py OUT.go: the _opcode module's tables (PY6a), go/arbace/py's builtins_opcode_table.go, recorded from the
# oracle (CPython 3.14.10's own _opcode over its _opcode_metadata.opmap; tools/pydump/PYTHON_VERSION pins it): each
# opcode's has_arg ... has_exc flags and validity, the intrinsics' and binary operators' descriptions, the special
# method names. Run: python3 -I -S -B tools/pyi/opcode_table.py OUT.go (bin/pyi checks the version first).
import sys
import _opcode
from _opcode_metadata import opmap

out = sys.argv[1]
preds = ["has_arg", "has_const", "has_name", "has_jump", "has_free", "has_local", "has_exc"]
rows = []
for op in range(0, 512):
    if not _opcode.is_valid(op) and op not in opmap.values():
        continue
    bits = 0
    for i, p in enumerate(preds):
        if getattr(_opcode, p)(op):
            bits |= 1 << i
    rows.append("%d:%d:%d" % (op, bits, 1 if _opcode.is_valid(op) else 0))


def strs(xs):
    return ", ".join('"%s"' % x for x in xs)


with open(out, "w") as o:
    o.write("// Code generated by tools/pyi/opcode_table.py from CPython %s's _opcode; DO NOT EDIT.\n\n" % sys.version.split()[0])
    o.write("package py\n\n")
    o.write("// opcodeRows are OP:FLAGS:VALID, FLAGS a bit per has_arg, has_const, has_name, has_jump, has_free, has_local, has_exc.\n")
    o.write("const opcodeRows = \"%s\"\n\n" % " ".join(rows))
    o.write("var opcodeIntrinsic1 = []string{%s}\n\n" % strs(_opcode.get_intrinsic1_descs()))
    o.write("var opcodeIntrinsic2 = []string{%s}\n\n" % strs(_opcode.get_intrinsic2_descs()))
    o.write("var opcodeSpecialMethods = []string{%s}\n\n" % strs(_opcode.get_special_method_names()))
    o.write("var opcodeNbOps = [][2]string{%s}\n" % ", ".join('{"%s", "%s"}' % (a, b) for a, b in _opcode.get_nb_ops()))
