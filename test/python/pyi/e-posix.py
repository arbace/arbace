# PY6e: posix's file and process functions (stat_result, utime, scandir, descriptors, sysconf, system), equal to CPython
import os, stat, sys
import shutil
d = os.path.join(os.environ.get("TMPDIR", "."), "e-posix-%d" % os.getpid()); shutil.rmtree(d, ignore_errors=True); os.mkdir(d)
p = os.path.join(d, 'f')
with open(p, 'wb') as f: f.write(b'abc')
st = os.stat(p)
print(stat.S_ISREG(st.st_mode), st.st_size, type(st.st_mtime).__name__, st.st_mtime_ns // 10**9 == st[8], len(st), st.n_fields)
os.utime(p, (1000000000.5, 1000000001.25)); st = os.stat(p); print(st.st_atime, st.st_mtime, st.st_mtime_ns)
os.utime(p, ns=(5*10**9+7, 6*10**9+9)); print(os.stat(p).st_mtime_ns)
os.mkdir(os.path.join(d, 'sub'), 0o700); print(oct(os.stat(os.path.join(d,'sub')).st_mode & 0o777))
os.symlink(p, os.path.join(d, 'ln')); print(os.readlink(os.path.join(d,'ln')) == p, os.path.islink(os.path.join(d,'ln')))
print(sorted(os.listdir(d)), sorted((e.name, e.is_dir(), e.is_file(), e.is_symlink()) for e in os.scandir(d)))
with os.scandir(d) as it: print(sorted(repr(e) for e in it))
os.chmod(p, 0o600); print(oct(os.stat(p).st_mode & 0o777), os.access(p, os.R_OK), os.access(d+'/nope', os.F_OK))
os.truncate(p, 1); print(os.path.getsize(p))
r, w = os.pipe(); print(os.get_inheritable(r), os.get_blocking(r)); os.set_inheritable(r, True); print(os.get_inheritable(r)); os.set_blocking(r, False); print(os.get_blocking(r))
os.write(w, b'xyz'); print(os.read(r, 10))
fd = os.open(p, os.O_RDWR); os.pwrite(fd, b'QQ', 3); print(os.pread(fd, 10, 0)); print(os.dup2(fd, 50, inheritable=False), os.get_inheritable(50))
os.close(fd); os.close(50)
print(os.sysconf('SC_IOV_MAX'), os.sysconf('SC_PAGE_SIZE'), os.confstr('CS_PATH'), os.pathconf('/', 'PC_NAME_MAX'))
print(type(os.uname()).__name__, os.uname().sysname, os.times().elapsed > 0, os.isatty(0))
print(os.statvfs('/').f_namemax, os.major(os.makedev(8, 1)), os.minor(os.makedev(8, 1)))
print(os.waitstatus_to_exitcode(os.system('exit 3')))
try: os.stat(d + '/missing')
except FileNotFoundError as e: print(e.errno, e.strerror, e.filename == d + '/missing')
try: os.rename(d+'/missing', d+'/x')
except FileNotFoundError as e: print(str(e).replace(d, 'D'))
print(os.stat_result(tuple(range(10))).st_atime, repr(os.stat_result(tuple(range(10)))))
print(os.cpu_count() > 0)
shutil.rmtree(d); print(os.path.exists(d))
