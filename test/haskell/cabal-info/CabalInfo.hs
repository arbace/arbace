-- CabalInfo (doc/haskell/HASKELL-NOTES.md, "R5"): how R5's packages in
-- test/haskell/corpus-ghc-9.14.1.edn got their configurations. `CabalInfo FILE.cabal [+flag|-flag...]`
-- prints the library's build info for linux/x86_64 and GHC 9.14.1, as Cabal configures it:
-- Cabal-syntax's finalizePD, the flags hadrian gives (src/Settings/Packages.hs: unix, directory
-- +os-string, ghci +internal-interpreter, text -simdutf, haskeline -examples +terminfo, ghc-boot
-- -bootstrap) and the others solved against the installed packages' versions (installed.txt,
-- `ghc-pkg list --simple-output`, one per line), one KEY<TAB>VALUE a line: the flags, the
-- language, the default extensions, cpp-options, include-dirs, hs-source-dirs, the modules,
-- the autogenerated ones, ghc-options, build-depends. A .cabal.in is read with configure's
-- substitutions (@ProjectVersionMunged@ 9.14.1, @ProjectVersionForLib@ 9.1401, @Suffix@ empty,
-- @SourceRoot@ .). Built by the host's GHC: ghc -package Cabal-syntax CabalInfo.hs.
import qualified Data.ByteString as B
import Distribution.PackageDescription
import Distribution.PackageDescription.Parsec
import Distribution.PackageDescription.Configuration
import Distribution.System
import Distribution.Compiler
import Distribution.Version
import Distribution.Types.ComponentRequestedSpec
import Distribution.Pretty (prettyShow)
import Distribution.Utils.Path (getSymbolicPath)
import Language.Haskell.Extension
import System.Environment
import Data.List (intercalate)
import Distribution.Types.DependencySatisfaction
import Distribution.Types.MissingDependencyReason
import Distribution.Types.Dependency
import Distribution.Types.PackageName
import Distribution.Parsec (simpleParsec)
import qualified Data.Map as M

main :: IO ()
main = do
  (f : fl) <- getArgs
  inst <- lines <$> readFile "installed.txt"
  let vers = M.fromList [ (reverse (drop 1 b), v) | l <- inst, let (a, b) = break (== '-') (reverse l), Just v <- [simpleParsec (reverse a)] ]
      sat d = case M.lookup (unPackageName (depPkgName d)) vers of
        Just v | withinRange v (depVerRange d) -> Satisfied
        _ -> Unsatisfied MissingPackage
  bs <- B.readFile f
  let (_, r) = runParseResult (parseGenericPackageDescription bs)
  gpd <- either (\e -> error (show e)) pure r
  let flags = mkFlagAssignment [ (mkFlagName (drop 1 x), head x == '+') | x <- fl ]
      cinfo = unknownCompilerInfo (CompilerId GHC (mkVersion [9, 14, 1])) NoAbiTag
  case finalizePD flags defaultComponentRequestedSpec sat (Platform X86_64 Linux) cinfo [] gpd of
    Left ds -> error (show ds)
    Right (pd, fa) -> do
      let Just lib = library pd
          bi = libBuildInfo lib
          w k v = putStrLn (k ++ "\t" ++ v)
      w "flags" (unwords [ (if b then "+" else "-") ++ unFlagName n | (n, b) <- unFlagAssignment fa ])
      w "language" (maybe "" prettyShow (defaultLanguage bi))
      w "extensions" (unwords (map prettyShow (defaultExtensions bi ++ oldExtensions bi)))
      w "cpp-options" (unwords (cppOptions bi))
      w "include-dirs" (unwords (map getSymbolicPath (includeDirs bi)))
      w "source-dirs" (unwords (map getSymbolicPath (hsSourceDirs bi)))
      w "exposed" (unwords (map prettyShow (exposedModules lib)))
      w "other" (unwords (map prettyShow (otherModules bi)))
      w "autogen" (unwords (map prettyShow (autogenModules bi)))
      w "ghc-options" (unwords (hcOptions GHC bi))
      w "depends" (unwords [ prettyShow d | d <- targetBuildDepends bi ])
